defmodule Precompiled.HostNativeTest do
  use ExUnit.Case, async: true
  alias Precompiled.{HostNative, Reason}
  @moduletag :tmp_dir

  @hex String.duplicate("ab", 32)
  @archive "libx-v1.0.0-nif-2.16-aarch64-unknown-linux-gnu.so.tar.gz"

  describe "triple/1" do
    test "Linux glibc on x86_64 or aarch64, aliases included" do
      for {arch, triple} <- [
            {"x86_64-pc-linux-gnu", "x86_64-linux-gnu"},
            {"x86_64-redhat-linux-gnu", "x86_64-linux-gnu"},
            {"x86_64-linux-gnu", "x86_64-linux-gnu"},
            {"amd64-pc-linux-gnu", "x86_64-linux-gnu"},
            {"aarch64-unknown-linux-gnu", "aarch64-linux-gnu"},
            {"arm64-unknown-linux-gnu", "aarch64-linux-gnu"}
          ] do
        assert HostNative.triple(arch) == triple, arch
      end
    end

    test "anything else is no host-native triple" do
      for arch <- [
            "x86_64-alpine-linux-musl",
            "x86_64-pc-linux-musl",
            "aarch64-apple-darwin24.6.0",
            "x86_64-apple-darwin23.0.0",
            "arm-unknown-linux-gnueabihf",
            "armv7l-unknown-linux-gnueabihf",
            "i686-pc-linux-gnu",
            "riscv64-unknown-linux-gnu",
            "x86_64-pc-linux-gnux32",
            "amd64-portbld-freebsd14.1",
            "win32",
            "linux-gnu",
            ""
          ] do
        assert HostNative.triple(arch) == nil, arch
      end
    end
  end

  @ldconfig """
  1203 libs found in cache `/etc/ld.so.cache'
  \tlibz.so.1 (libc6,x86-64) => /lib/x86_64-linux-gnu/libz.so.1
  \tlibz.so.1 (libc6) => /lib/i386-linux-gnu/libz.so.1
  \tlibssl.so.3 (libc6,x86-64) => /usr/local/lib/libssl.so.3
  \tlibfoo.so.2 (libc6,x86-64, OS ABI: Linux 3.2.0) => /opt/foo/lib/libfoo.so.2
  \tlibbar.so.1 (libc6,AArch64) => /usr/lib/aarch64-linux-gnu/libbar.so.1
  \tlibc.so.6 (libc6,x86-64, hwcap: 0x0000000000000004) => /lib/x86_64-linux-gnu/libc.so.6
  \tbroken line without arrow
  \tlibrel.so (libc6,x86-64) => relative/librel.so
  Cache generated by: ldconfig (GNU libc) stable release version 2.36
  """

  test "ldconfig_dirs/2: the dirs of this triple's entries, in order, once each" do
    assert HostNative.ldconfig_dirs(@ldconfig, "x86_64-linux-gnu") == [
             "/lib/x86_64-linux-gnu",
             "/usr/local/lib",
             "/opt/foo/lib"
           ]

    assert HostNative.ldconfig_dirs(@ldconfig, "aarch64-linux-gnu") == [
             "/usr/lib/aarch64-linux-gnu"
           ]

    assert HostNative.ldconfig_dirs(nil, "x86_64-linux-gnu") == []
    assert HostNative.ldconfig_dirs("garbage", "x86_64-linux-gnu") == []
  end

  test "lib_roots/2: ldconfig's dirs, then the multiarch and /lib* dirs that exist" do
    existing =
      MapSet.new([
        "/lib/x86_64-linux-gnu",
        "/opt/foo/lib",
        "/lib64",
        "/usr/lib/x86_64-linux-gnu",
        "/lib",
        "/usr/lib"
      ])

    roots =
      HostNative.lib_roots("x86_64-linux-gnu",
        ldconfig: @ldconfig,
        dir?: &MapSet.member?(existing, &1)
      )

    assert roots == [
             "/lib/x86_64-linux-gnu",
             "/opt/foo/lib",
             "/lib64",
             "/usr/lib/x86_64-linux-gnu",
             "/lib",
             "/usr/lib"
           ]

    assert HostNative.lib_roots("aarch64-linux-gnu", ldconfig: nil, dir?: fn _ -> true end) ==
             [
               "/lib64",
               "/usr/lib64",
               "/lib/aarch64-linux-gnu",
               "/usr/lib/aarch64-linux-gnu",
               "/lib",
               "/usr/lib"
             ]
  end

  test "host/0 reads this VM" do
    host = HostNative.host()
    arch = List.to_string(:erlang.system_info(:system_architecture))
    assert host.system_architecture == arch
    assert host.triple == HostNative.triple(arch)
    assert host.nif_version == List.to_string(:erlang.system_info(:nif_version))
    otp = List.to_string(:erlang.system_info(:otp_release))
    assert host.otp_full in [nil, otp] or String.starts_with?(host.otp_full, otp <> ".")
    if host.triple == nil, do: assert(host.lib_roots == [])
  end

  describe "checksum_file/1, as data" do
    defp write(dir, name, text) do
      path = Path.join(dir, name)
      File.write!(path, text)
      path
    end

    test "a literal map of names to sha256 strings", %{tmp_dir: dir} do
      path =
        write(dir, "checksum.exs", """
        %{
          "#{@archive}" => "sha256:#{@hex}",
          "other.tar.gz" => "sha256:#{String.duplicate("0", 64)}",
        }
        """)

      assert {:ok, map} = HostNative.checksum_file(path)
      assert map[@archive] == "sha256:" <> @hex
      assert map_size(map) == 2
    end

    test "code is never evaluated, and is no checksum file", %{tmp_dir: dir} do
      marker = Path.join(dir, "evaluated")

      for text <- [
            ~s|File.write!("#{marker}", "x")|,
            ~s|%{"a" => File.write!("#{marker}", "x")}|,
            ~s|%{File.write!("#{marker}", "x") => "sha256:#{@hex}"}|,
            ~s|(File.write!("#{marker}", "x"); %{"a" => "sha256:#{@hex}"})|,
            ~s|%{"a" => "sha256:\#{File.write!("#{marker}", "x")}"}|
          ] do
        path = write(dir, "checksum.exs", text)
        assert {:error, _} = HostNative.checksum_file(path), text
      end

      refute File.exists?(marker)
    end

    test "anything but a literal string map of sha256 strings is refused", %{tmp_dir: dir} do
      for text <- [
            ~s|["#{@archive}", "sha256:#{@hex}"]|,
            ~s|%{a: "sha256:#{@hex}"}|,
            ~s|%{"a" => "#{@hex}"}|,
            ~s|%{"a" => "sha256:#{String.upcase(@hex)}"}|,
            ~s|%{"a" => "sha256:abc"}|,
            ~s|%{"a" => 1}|,
            ~s|%{"a" => "sha256:#{@hex}", "b" => nil}|,
            ~s|%{"a" => "sha256:#{@hex}"} %{}|,
            "%{\"a\" => ",
            ""
          ] do
        path = write(dir, "checksum.exs", text)
        assert {:error, _} = HostNative.checksum_file(path), text
      end
    end

    test "a missing, oversized or non-regular file is refused", %{tmp_dir: dir} do
      assert {:error, _} = HostNative.checksum_file(Path.join(dir, "none.exs"))
      assert {:error, _} = HostNative.checksum_file(dir)

      big =
        write(
          dir,
          "big.exs",
          ~s|%{"a" => "sha256:#{@hex}"}| <> String.duplicate(" ", 1_048_576)
        )

      assert {:error, _} = HostNative.checksum_file(big)
    end
  end

  describe "origins_reason/3" do
    defp origin(over \\ %{}) do
      Map.merge(
        %{
          "path" => "priv/native/libx.so",
          "checksum_file" => "checksum-Elixir.X.Native.exs",
          "archive" => @archive,
          "archive_sha256" => @hex
        },
        over
      )
    end

    defp deps(dir, file \\ "checksum-Elixir.X.Native.exs", text) do
      File.mkdir_p!(Path.join([dir, "deps", "x"]))
      File.write!(Path.join([dir, "deps", "x", file]), text)
      Path.join(dir, "deps")
    end

    test "every archive listed with its sha256 passes; none to check passes", %{tmp_dir: dir} do
      deps = deps(dir, ~s|%{"#{@archive}" => "sha256:#{@hex}"}|)
      assert HostNative.origins_reason([origin()], deps, "x") == :ok
      assert HostNative.origins_reason([], deps, "x") == :ok

      File.write!(
        Path.join([deps, "x", "checksum.exs"]),
        ~s|%{"#{@archive}" => "sha256:#{@hex}"}|
      )

      assert HostNative.origins_reason([origin(%{"checksum_file" => "checksum.exs"})], deps, "x") ==
               :ok
    end

    test "another sha256, or an archive the file does not list", %{tmp_dir: dir} do
      deps = deps(dir, ~s|%{"#{@archive}" => "sha256:#{String.duplicate("0", 64)}"}|)

      assert {:miss, %Reason{code: :origin_unverified, text: text}} =
               HostNative.origins_reason([origin()], deps, "x")

      assert text == "#{@archive} not in the package's checksum file"

      assert {:miss, %Reason{code: :origin_unverified}} =
               HostNative.origins_reason([origin(%{"archive" => "y.tar.gz"})], deps, "x")
    end

    test "a missing, unparseable or code checksum file", %{tmp_dir: dir} do
      assert {:miss, %Reason{code: :origin_unverified, args: ["checksum-Elixir.X.Native.exs"]}} =
               HostNative.origins_reason([origin()], Path.join(dir, "deps"), "x")

      for text <- ["%{", ~s|System.halt(1)|, ~s|[1, 2]|] do
        deps = deps(dir, text)

        assert {:miss, %Reason{code: :origin_unverified}} =
                 HostNative.origins_reason([origin()], deps, "x"),
               text
      end
    end

    test "a checksum file name that is not a plain checksum*.exs basename", %{tmp_dir: dir} do
      deps = deps(dir, ~s|%{"#{@archive}" => "sha256:#{@hex}"}|)
      File.write!(Path.join(dir, "checksum.exs"), ~s|%{"#{@archive}" => "sha256:#{@hex}"}|)

      for name <- [
            "../checksum.exs",
            "../../checksum.exs",
            "sub/checksum.exs",
            "/etc/checksum.exs",
            "checksum.ex",
            "mix.exs",
            "checksum-a/b.exs",
            "checksum-.exs",
            ".checksum.exs"
          ] do
        assert {:miss, %Reason{code: :origin_unverified}} =
                 HostNative.origins_reason([origin(%{"checksum_file" => name})], deps, "x"),
               name
      end
    end

    test "origins that are not a list of complete entries are malformed", %{tmp_dir: dir} do
      deps = deps(dir, ~s|%{"#{@archive}" => "sha256:#{@hex}"}|)

      for bad <- [
            nil,
            %{},
            "x",
            [nil],
            [Map.delete(origin(), "archive")],
            [origin(%{"archive_sha256" => 1})]
          ] do
        assert {:miss, %Reason{code: :malformed_entry}} =
                 HostNative.origins_reason(bad, deps, "x"),
               inspect(bad)
      end
    end
  end

  test "nif_reason/2: no newer than this VM's" do
    assert HostNative.nif_reason("2.16", "2.17") == :ok
    assert HostNative.nif_reason("2.17", "2.17") == :ok
    assert HostNative.nif_reason("2.9", "2.17") == :ok

    assert {:miss, %Reason{code: :nif_version_newer, args: ["2.17", "2.16"]}} =
             HostNative.nif_reason("2.17", "2.16")

    assert {:miss, %Reason{code: :nif_version_newer}} = HostNative.nif_reason("3.0", "2.17")

    for bad <- [nil, 2.17, "", "2.x", "two"] do
      assert {:miss, %Reason{code: :malformed_entry}} = HostNative.nif_reason(bad, "2.17")
    end
  end
end
